#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Atlas Project - Return to the last version that deployed successfully
# ==============================================================================
# Code only: the database is kept as is. To restore data from a dump, see
# "Rolling back a bad deploy" in README.md.

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJECT_DIR"

LAST_GOOD=$(cat backups/last-good-commit 2>/dev/null || true)
if [ -z "$LAST_GOOD" ]; then
    echo "[ERROR] No successful deploy recorded yet (backups/last-good-commit), nothing to roll back to."
    exit 1
fi

if [ "$LAST_GOOD" = "$(git rev-parse HEAD)" ]; then
    echo "[INFO] Already on the last working version ($(git log -1 --format='%h %s')), nothing to do."
    exit 0
fi

echo "[INFO] Rolling back: $(git log -1 --format='%h %s') -> $(git log -1 --format='%h %s' "$LAST_GOOD")"

# Generated by deploy.sh, so its local changes would block the checkout
git checkout -- keycloak/atlas-frontend.json
git checkout --detach "$LAST_GOOD"

exec ./deploy.sh "$@"
