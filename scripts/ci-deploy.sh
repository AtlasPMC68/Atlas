#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Atlas Project - Automatic deploy, called by GitHub Actions over SSH
# ==============================================================================
# The deploy key in ~/.ssh/authorized_keys is restricted to this script:
#   restrict,command="/home/ubuntu/atlas/scripts/ci-deploy.sh" ssh-ed25519 AAAA... github-deploy
# GitHub sends the commit SHA as the SSH command, which arrives here in
# SSH_ORIGINAL_COMMAND. It can also be run by hand: ./scripts/ci-deploy.sh <sha>
#
# Only commits already on origin/main are accepted. If deploy.sh fails, the
# last working version is redeployed with rollback.sh and the script exits 1.
# See "Déploiement automatique" in docs/deploiement/README.md.

# Everything lives in main(): bash reads scripts as it runs them, and the
# git checkout below can replace this very file. Parsing the whole function
# first keeps the running copy intact.
main() {
    local project_dir sha lock_file log_file
    project_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
    cd "$project_dir"

    sha="${SSH_ORIGINAL_COMMAND:-${1:-}}"
    if ! [[ "$sha" =~ ^[0-9a-f]{40}$ ]]; then
        echo "[ERROR] Expected a full 40-character commit SHA, got: '${sha}'"
        exit 2
    fi

    mkdir -p backups && chmod 700 backups
    log_file="$project_dir/backups/ci-deploy.log"
    # Keep a copy of the output on the server, next to the database backups
    exec > >(tee -a "$log_file") 2>&1
    echo "================================================================================"
    echo "[INFO] $(date -u +%Y-%m-%dT%H:%M:%SZ) automatic deploy of $sha"

    # One deploy at a time, including manual ./deploy.sh runs started through this script
    lock_file="$project_dir/backups/.deploy.lock"
    exec 9>"$lock_file"
    if ! flock -w 1800 9; then
        echo "[ERROR] Another deploy has held the lock for 30 minutes, giving up."
        exit 1
    fi

    echo "[INFO] Fetching origin/main..."
    git fetch --quiet origin main

    if ! git cat-file -e "${sha}^{commit}" 2>/dev/null; then
        echo "[ERROR] Commit $sha does not exist on origin."
        exit 2
    fi
    if ! git merge-base --is-ancestor "$sha" origin/main; then
        echo "[ERROR] Commit $sha is not on origin/main, refusing to deploy it."
        exit 2
    fi

    # Generated by deploy.sh, so its local changes would block the checkout
    git checkout --quiet -- keycloak/atlas-frontend.json
    git checkout --quiet --detach "$sha"
    echo "[INFO] Now on $(git log -1 --format='%h %s')"

    if ./deploy.sh; then
        echo "[SUCCESS] Automatic deploy of $(git rev-parse --short HEAD) finished."
        exit 0
    fi

    echo "[ERROR] deploy.sh failed for $sha, rolling back to the last working version..."
    if ./rollback.sh; then
        echo "[ERROR] Rolled back to $(git log -1 --format='%h %s'). The site runs the previous version."
    else
        echo "[ERROR] Rollback failed too: the site may be down. Connect to the server and check 'docker compose ps -a'."
    fi
    # Red job in GitHub either way: the merged commit is not what runs in production
    exit 1
}

main "$@"
exit
