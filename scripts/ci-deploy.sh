#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Atlas Project - Automatic deploy, called by GitHub Actions over SSH
# ==============================================================================
# The deploy key in ~/.ssh/authorized_keys is restricted to this script:
#   restrict,command="/home/ubuntu/atlas/scripts/ci-deploy.sh" ssh-ed25519 AAAA... github-deploy
# GitHub sends the commit SHA as the SSH command, which arrives here in
# SSH_ORIGINAL_COMMAND. It can also be run by hand: ./scripts/ci-deploy.sh <sha>
#
# Only commits on origin/main are accepted, and never one older than the
# version already deployed. If deploy.sh fails, the last working version is
# redeployed with rollback.sh and the script exits 1.
# Requires a first manual ./deploy.sh (it creates .env).
# See "Déploiement automatique" in docs/deploiement/README.md.

# Everything lives in main(): bash reads scripts as it runs them, and the
# git checkout below can replace this very file. Parsing the whole function
# first keeps the running copy intact.
main() {
    local project_dir sha lock_file log_file last_good domain ip
    project_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
    cd "$project_dir"

    # The SSH connection can drop mid-deploy (network cut, job cancelled,
    # timeout-minutes reached). Ignore the hangup and broken pipe signals,
    # inherited by deploy.sh and docker, so the deploy always runs to the end
    # (or to its rollback) instead of stopping halfway, e.g. after the checkout.
    trap '' HUP PIPE

    sha="${SSH_ORIGINAL_COMMAND:-${1:-}}"
    if ! [[ "$sha" =~ ^[0-9a-f]{40}$ ]]; then
        echo "[ERROR] Expected a full 40-character commit SHA, got: '${sha}'"
        exit 2
    fi

    mkdir -p backups && chmod 700 backups

    # One deploy at a time. Taken before logging so two runs never mix their lines.
    lock_file="$project_dir/backups/.deploy.lock"
    exec 9>"$lock_file"
    if ! flock -w 1800 9; then
        echo "[ERROR] Another deploy has held the lock for 30 minutes, giving up." >&2
        exit 1
    fi

    # Keep a copy of the output on the server, next to the database backups.
    # -p: if GitHub disconnects, tee keeps writing the log file instead of dying,
    # so the script's own writes never fail on a closed pipe.
    log_file="$project_dir/backups/ci-deploy.log"
    exec > >(tee -p -a "$log_file") 2>&1
    echo "================================================================================"
    echo "[INFO] $(date -u +%Y-%m-%dT%H:%M:%SZ) automatic deploy of $sha"

    # Reuse the server's address from .env: without an argument, deploy.sh would
    # detect the public IP again and rewrite every URL in .env if it got another one
    domain=$(grep -E '^DOMAIN=' .env 2>/dev/null | cut -d= -f2- || true)
    ip="${domain%.nip.io}"
    if [ -z "$domain" ] || [ "$ip" = "$domain" ]; then
        echo "[ERROR] No DOMAIN=<ip>.nip.io line in $project_dir/.env."
        echo "        Automatic deploys need a first manual deploy: run ./deploy.sh on the server once."
        exit 1
    fi

    echo "[INFO] Fetching origin/main..."
    git fetch --quiet origin main

    if ! git cat-file -e "${sha}^{commit}" 2>/dev/null; then
        echo "[ERROR] Commit $sha does not exist on origin."
        exit 2
    fi
    if ! git merge-base --is-ancestor "$sha" origin/main; then
        echo "[ERROR] Commit $sha is not on origin/main, refusing to deploy it."
        exit 2
    fi

    # Two merges close together: their tests run in parallel, so the newer one can
    # deploy first. Never go back to an older commit (redeploying the same one is fine).
    last_good=$(cat backups/last-good-commit 2>/dev/null || true)
    if [ -n "$last_good" ] && [ "$sha" != "$last_good" ] \
        && git merge-base --is-ancestor "$sha" "$last_good" 2>/dev/null; then
        echo "[INFO] A newer commit ($(git log -1 --format='%h %s' "$last_good")) is already deployed, skipping $sha"
        exit 0
    fi

    # Generated by deploy.sh, so its local changes would block the checkout
    git checkout --quiet -- keycloak/atlas-frontend.json
    git checkout --quiet --detach "$sha"
    echo "[INFO] Now on $(git log -1 --format='%h %s')"

    if ./deploy.sh "$ip"; then
        echo "[SUCCESS] Automatic deploy of $(git rev-parse --short HEAD) finished."
        exit 0
    fi

    echo "[ERROR] deploy.sh failed for $sha."
    if [ -z "$last_good" ] || [ "$last_good" = "$sha" ]; then
        # Nothing older to return to: rollback.sh would only say "nothing to do"
        echo "[ERROR] Rollback impossible: no previous working version to return to."
        echo "        The site may be down. Connect to the server and check 'docker compose ps -a'."
    elif ./rollback.sh "$ip"; then
        echo "[ERROR] Rolled back to $(git log -1 --format='%h %s'). The site runs the previous version."
    else
        echo "[ERROR] Rollback failed too: the site may be down. Connect to the server and check 'docker compose ps -a'."
    fi
    # Red job in GitHub either way: the merged commit is not what runs in production
    exit 1
}

main "$@"
exit
